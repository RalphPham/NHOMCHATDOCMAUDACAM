    private void btnxoaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnxoaActionPerformed
        // TODO add your handling code here:
        String MaNV = txtma.getText().trim();
        if (MaNV.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập mã nhân viên!", "Thông báo", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this,
                "Bạn có chắc muốn xóa nhân viên với mã: " + MaNV + "?",
                "Xác nhận",
                JOptionPane.YES_NO_OPTION);

        if (confirm == JOptionPane.YES_OPTION) {
            NhanVien nv = new NhanVien();
            nv.setMaNV(MaNV);

            NhanVienDAO deleteNV = new NhanVienDAO();
            boolean result = deleteNV.delete(nv);

            if (result) {
                JOptionPane.showMessageDialog(this, "Xóa thành công!", "Thông báo", JOptionPane.INFORMATION_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this, "Mã Nhân viên không tồn tại, xóa thắt bại", "Lỗi", JOptionPane.ERROR_MESSAGE);
                return;
            }
        }
        fillTable();
    }//GEN-LAST:event_btnxoaActionPerformed

