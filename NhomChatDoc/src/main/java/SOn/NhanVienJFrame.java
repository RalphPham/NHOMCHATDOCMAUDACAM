    private void btnthemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnthemActionPerformed
        // TODO add your handling code here:
        if (txtma.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Mã Nhân Viên Không Được Để Trống.");
            return;
        }
        NhanVienDAO nvdao = new NhanVienDAO();

        // Kiểm tra mã nhân viên có bị trùng không
        if (nvdao.checkMaNV(txtma.getText())) {
            JOptionPane.showMessageDialog(this, "Mã Nhân Viên đã tồn tại! Vui lòng nhập mã khác.");
            return;
        }
        if (txtten.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Tên Nhân Viên Không Được Để Trống.");
            return;
        }
        if (txtemail.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Email Nhân Viên Không Được Để Trống.");
            return;
        }
        if (!txtemail.getText().matches("^[A-Za-z0-9+_.-]+@gmail\\.com$")) {
            JOptionPane.showMessageDialog(this, "Email không hợp lệ. Vui lòng nhập đúng định dạng *@gmail.com*.");
            return;
        }
        if (txtsdt.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Số Điện thoại Nhân Viên Không Được Để Trống.");
            return;
        }
        if (!txtsdt.getText().matches("0\\d{9}")) {
            JOptionPane.showMessageDialog(this, "Số điện thoại không hợp lệ (phải có 10 chữ số và bắt đầu bằng 0).");
            return;
        }
        if (!rdonam.isSelected() && !rdonu.isSelected()) {
            JOptionPane.showMessageDialog(this, "Giới Tính Nhân Viên Không Được Để Trống.");
            return;
        }
        if (txtdiachi.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Địa Chỉ Nhân Viên Không Được Để Trống.");
            return;
        }
        if (txtngaysinh.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ngày Sinh Nhân Viên Không Được Để Trống.");
            return;
        }
        try {
            NhanVien nv = new NhanVien();
            nv.setMaNV(txtma.getText());
            nv.setTenNV(txtten.getText());
            nv.setEmail(txtemail.getText());
            nv.setSDT(txtsdt.getText());
            if (rdonam.isSelected()) {
                nv.setGioiTinh("Nam");
            } else {
                nv.setGioiTinh("Nữ");
            }
            nv.setDiaChi(txtdiachi.getText());
            try {
                SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
                sdf.setLenient(false);
                Date utilDate = sdf.parse(txtngaysinh.getText().trim());
                nv.setNgaySinh(new java.sql.Date(utilDate.getTime()));
            } catch (ParseException ex) {
                JOptionPane.showMessageDialog(this, "Ngày sinh không hợp lệ. Định dạng đúng: yyyy-MM-dd.");
                return;
            }

            int chon = JOptionPane.showConfirmDialog(this, "Bạn có muốn thêm Nhân Viên", "Thông báo", JOptionPane.YES_NO_OPTION);
            if (chon == JOptionPane.YES_OPTION) {
                if (nvdao.insert(nv)) {
                    JOptionPane.showMessageDialog(this, "Thêm Nhân Viên thành công", "Thông báo", JOptionPane.INFORMATION_MESSAGE);
                    fillTable();
                } else {
                    JOptionPane.showMessageDialog(this, "Thêm Nhân Viên thất bại", "Thông báo", JOptionPane.ERROR_MESSAGE);
                    return;
                }
            }
        } catch (Exception e) {
            e.printStackTrace();
        }

    }//GEN-LAST:event_btnthemActionPerformed

